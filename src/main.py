                            # Проверяем, что в новом подразделении есть место
                            valid_available = [
                                a for a in available
                                if current_staff.get(a['Код подразделения'], {}).get(block, 0) < 
                                   initial_staff.get(a['Код подразделения'], {}).get(block, 0)
                            ]
                            
